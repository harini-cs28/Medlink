"""
MedPredict AI - Main Feature Engineering Pipeline Orchestrator
Builds end-to-end feature matrices for demand forecasting and shortage risk prediction.
"""

from pathlib import Path
from typing import List, Optional
import pandas as pd

from src.features.demand_features import (
    create_calendar_features,
    create_lag_features,
    create_rolling_features,
    create_demand_momentum_features
)
from src.features.shortage_features import (
    extract_shortage_duration,
    compute_drug_shortage_frequency,
    compute_reason_distribution
)

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent


def build_forecasting_feature_matrix(
    sales_df: pd.DataFrame,
    target_columns: Optional[List[str]] = None,
    save_path: Optional[str | Path] = None
) -> pd.DataFrame:
    """
    Constructs comprehensive time-series feature matrix for pharma demand forecasting.
    """
    df = sales_df.copy()
    
    # Identify target numerical sales columns if not explicitly provided
    if target_columns is None:
        numeric_cols = df.select_dtypes(include=['number']).columns.tolist()
        target_columns = [c for c in numeric_cols if not c.startswith(('day', 'month', 'year', 'quarter', 'is_'))]
        
    print(f"[FEATURE ENG] Generating features for target series: {target_columns}")
    
    # 1. Calendar & seasonal features
    df = create_calendar_features(df, date_col='date')
    
    # 2. Lag features
    df = create_lag_features(df, target_cols=target_columns, lags=[1, 2, 3, 7, 14, 21, 28])
    
    # 3. Rolling window statistics
    df = create_rolling_features(df, target_cols=target_columns, windows=[7, 14, 30])
    
    # 4. Momentum & acceleration
    df = create_demand_momentum_features(df, target_cols=target_columns)
    
    # Drop initial rows with NaNs generated by the longest lag window
    df = df.dropna().reset_index(drop=True)
    
    if save_path:
        out_file = Path(save_path)
        out_file.parent.mkdir(parents=True, exist_ok=True)
        df.to_csv(out_file, index=False)
        print(f"[INFO] Feature matrix saved to: {out_file}")
        
    return df


def build_shortage_feature_matrix(
    shortages_df: pd.DataFrame,
    save_path: Optional[str | Path] = None
) -> pd.DataFrame:
    """
    Constructs feature matrix for shortage classification analysis.
    """
    df = shortages_df.copy()
    df = extract_shortage_duration(df)
    df = compute_drug_shortage_frequency(df)
    df = compute_reason_distribution(df)
    
    if save_path:
        out_file = Path(save_path)
        out_file.parent.mkdir(parents=True, exist_ok=True)
        df.to_csv(out_file, index=False)
        print(f"[INFO] Shortage feature matrix saved to: {out_file}")
        
    return df
